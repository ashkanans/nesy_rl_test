import numpy as np
import torch
from torch.utils.data import Dataset

from envs.colour_bomb import (
    CBConfig,
    ColourBombGridworldV1Env,
    compute_cb_longest_safe_path_actions,
    compute_cb_shortest_safe_policy,
)
from logic.token_schema import (
    build_end_row,
    get_end_token_id,
    get_num_bins_per_dim,
    get_schema_for_env,
    make_transition_row,
    validate_episode_tokens,
)


class CBSequenceDataset(Dataset):
    """
    Sequence dataset for Colour Bomb Gridworld v1.

    Each episode is generated by taking random actions in the gridworld.
    For each timestep t we store a 4-dimensional "transition token":
        [state_t, action_t, 0, 0]
    so that:
        observation_dim = 1
        action_dim      = 1
        joined_dim      = 4

    These flattened transitions are sliced into fixed-length sequences:
        x: seq_len tokens
        y: next-token targets
        mask: 1 for all positions (no padding here).
    """

    def __init__(
        self,
        num_episodes=1000,
        max_steps=200,
        sequence_length=200,
        discount=0.99,
        stochastic=False,
        seed=0,
        target_shift="token",
        policy_mix_spec="random:1.0",
        policy_mix_sampling="fixed",
        policy_mix_normal_spec=None,
        state_semantics="post",
        longest_path_max_expansions=500000,
    ):
        self.sequence_length = sequence_length
        self.discount = discount
        self.target_shift = str(target_shift)
        self.policy_mix_spec = str(policy_mix_spec)
        self.policy_mix_sampling = str(policy_mix_sampling)
        self.policy_mix_normal_spec = (
            None if policy_mix_normal_spec is None else str(policy_mix_normal_spec)
        )
        self.state_semantics = str(state_semantics)
        self.longest_path_max_expansions = int(longest_path_max_expansions)
        if self.target_shift not in {"token", "transition"}:
            raise ValueError("target_shift must be 'token' or 'transition'.")
        if self.policy_mix_sampling not in {"fixed", "normal"}:
            raise ValueError("policy_mix_sampling must be 'fixed' or 'normal'.")
        if self.state_semantics not in {"pre", "post"}:
            raise ValueError("state_semantics must be 'pre' or 'post'.")
        self.token_schema = get_schema_for_env("cb")
        self.schema_id = self.token_schema.schema_id

        cfg = CBConfig(max_steps=max_steps, stochastic=stochastic)
        self.env = ColourBombGridworldV1Env(cfg)
        self.num_bins_per_dim = get_num_bins_per_dim(
            self.token_schema, self.env.observation_space.n, self.env.action_space.n
        )
        self.end_token_id = get_end_token_id(
            self.token_schema, self.env.observation_space.n, self.env.action_space.n
        )

        rng = np.random.RandomState(seed)
        mix_names, mix_probs = _parse_policy_mix_spec(self.policy_mix_spec)
        self.policy_mix_names = mix_names
        self.policy_mix_probs = mix_probs
        self.policy_mix_normal_params = _parse_policy_mix_normal_spec(
            self.policy_mix_normal_spec, self.policy_mix_names, self.policy_mix_probs
        )
        self.shortest_safe_policy = compute_cb_shortest_safe_policy(self.env, avoid_bombs=True)
        self.shortest_any_policy = compute_cb_shortest_safe_policy(self.env, avoid_bombs=False)
        self.longest_safe_path = compute_cb_longest_safe_path_actions(
            self.env, avoid_bombs=True, max_expansions=self.longest_path_max_expansions
        )
        self.longest_any_path = compute_cb_longest_safe_path_actions(
            self.env, avoid_bombs=False, max_expansions=self.longest_path_max_expansions
        )

        episodes_tokens = []
        episode_rewards = []
        episode_policy_labels = []

        for _ in range(num_episodes):
            s, _ = self.env.reset()
            states = []
            actions = []
            rewards = []
            sampled_probs = _sample_policy_probs(
                rng=rng,
                names=self.policy_mix_names,
                base_probs=self.policy_mix_probs,
                mode=self.policy_mix_sampling,
                normal_params=self.policy_mix_normal_params,
            )
            policy_name = str(rng.choice(self.policy_mix_names, p=sampled_probs))
            path_step = 0

            for t in range(max_steps):
                pre_s = int(s)
                a = _choose_action(
                    env=self.env,
                    rng=rng,
                    state=pre_s,
                    policy_name=policy_name,
                    path_step=path_step,
                    shortest_safe_policy=self.shortest_safe_policy,
                    shortest_any_policy=self.shortest_any_policy,
                    longest_safe_path=self.longest_safe_path,
                    longest_any_path=self.longest_any_path,
                )
                ns, r, done, _ = self.env.step(a)
                token_state = int(pre_s if self.state_semantics == "pre" else ns)
                states.append(token_state)
                actions.append(a)
                rewards.append(r)
                s = ns
                path_step += 1
                if done:
                    break

            T = len(states)
            if T == 0:
                continue

            tokens = np.zeros((T, self.token_schema.width), dtype=np.int64)
            for t in range(T):
                tokens[t] = make_transition_row(
                    schema=self.token_schema,
                    state=int(states[t]),
                    action=int(actions[t]),
                    reward_token=0,
                    safety_cost=0,
                )

            # append exactly one explicit END marker at trace level
            # (state position only; other dims are neutral fillers)
            end_row = build_end_row(self.token_schema, self.end_token_id)
            tokens = np.vstack([tokens, end_row])
            validate_episode_tokens(
                tokens,
                schema=self.token_schema,
                end_token_id=self.end_token_id,
                observation_space_n=self.env.observation_space.n,
                action_space_n=self.env.action_space.n,
            )

            episodes_tokens.append(tokens)
            episode_rewards.append(np.asarray(rewards, dtype=np.float32))
            episode_policy_labels.append(policy_name)

        indices = []
        self.rows_per_seg = max(1, sequence_length // self.token_schema.width)
        self.required_rows = (
            self.rows_per_seg + 1 if self.target_shift == "transition" else max(2, self.rows_per_seg)
        )
        for ep_idx, rows in enumerate(episodes_tokens):
            R = rows.shape[0]
            if R < self.required_rows:
                continue
            starts = list(range(0, max(1, R - self.required_rows), self.rows_per_seg))
            tail = R - self.required_rows
            if tail not in starts:
                starts.append(tail)
            for start_row in starts:
                indices.append((ep_idx, start_row))

        self.episodes_tokens = episodes_tokens
        self.episode_rewards = episode_rewards
        self.episode_policy_labels = episode_policy_labels
        self.indices = indices

        self.observation_dim = 1
        self.action_dim = 1
        self.joined_dim = self.token_schema.width

    def __len__(self):
        return len(self.indices)

    def __getitem__(self, idx):
        ep_idx, start_row = self.indices[idx]
        rows = self.episodes_tokens[ep_idx]
        seg_rows = rows[start_row : start_row + self.required_rows]
        flat = seg_rows.reshape(-1)
        if self.target_shift == "token":
            x = torch.from_numpy(flat[:-1].astype(np.int64))
            y = torch.from_numpy(flat[1:].astype(np.int64))
        else:
            x = torch.from_numpy(flat[: -self.joined_dim].astype(np.int64))
            y = torch.from_numpy(flat[self.joined_dim :].astype(np.int64))
        mask = torch.ones_like(x, dtype=torch.float32)
        return x, y, mask


def _parse_policy_mix_spec(spec: str):
    """
    Parse strings like:
      random:0.8,shortest_safe:0.1,longest_safe:0.1
    """
    allowed = {
        "random",
        "shortest_safe",
        "longest_safe",
        "shortest_any",
        "longest_any",
    }
    raw = str(spec or "").strip()
    if not raw:
        return ["random"], [1.0]
    parts = [p.strip() for p in raw.split(",") if p.strip()]
    weights = []
    for p in parts:
        if ":" not in p:
            raise ValueError(f"Invalid policy mix token '{p}'. Expected name:weight.")
        name, w = p.split(":", 1)
        name = name.strip()
        if name not in allowed:
            raise ValueError(f"Unsupported CB policy '{name}'. Allowed: {sorted(allowed)}")
        val = float(w.strip())
        if val < 0.0:
            raise ValueError("Policy mix weights must be non-negative.")
        weights.append((name, val))
    total = sum(w for _, w in weights)
    if total <= 0.0:
        raise ValueError("Policy mix weights sum to zero.")
    names = [n for n, _ in weights]
    probs = [w / total for _, w in weights]
    return names, probs


def _parse_policy_mix_normal_spec(spec, names, base_probs):
    """
    Parse optional per-policy normal params:
      random:0.6:0.1,shortest_safe:0.3:0.08,longest_safe:0.1:0.05
    Missing policies fall back to mean=base_prob, std=0.05.
    """
    params = {str(n): (float(p), 0.05) for n, p in zip(names, base_probs)}
    if spec is None:
        return params
    raw = str(spec).strip()
    if raw == "":
        return params
    tokens = [t.strip() for t in raw.split(",") if t.strip()]
    for tok in tokens:
        parts = [p.strip() for p in tok.split(":")]
        if len(parts) != 3:
            raise ValueError(
                f"Invalid cb_policy_mix_normal_spec token '{tok}'. Expected name:mean:std."
            )
        name, mean_s, std_s = parts
        if name not in params:
            # Allow superset normal-spec configs across multiple runs/mixes.
            # Unknown names are ignored for this dataset instance.
            continue
        mean = float(mean_s)
        std = float(std_s)
        if std < 0.0:
            raise ValueError("Normal std must be non-negative.")
        params[name] = (mean, std)
    return params


def _sample_policy_probs(rng, names, base_probs, mode, normal_params):
    if mode == "fixed":
        return list(base_probs)

    weights = []
    for name in names:
        mean, std = normal_params.get(name, (0.0, 0.05))
        sample = float(rng.normal(loc=mean, scale=std))
        weights.append(max(0.0, sample))

    total = float(np.sum(weights))
    if total <= 0.0:
        # Fallback to deterministic base mix.
        return list(base_probs)
    return [w / total for w in weights]


def _choose_action(
    env: ColourBombGridworldV1Env,
    rng: np.random.RandomState,
    state: int,
    policy_name: str,
    path_step: int,
    shortest_safe_policy: dict[int, int],
    shortest_any_policy: dict[int, int],
    longest_safe_path: list[int],
    longest_any_path: list[int],
) -> int:
    if policy_name == "random":
        return int(rng.randint(env.action_space.n))
    if policy_name == "shortest_safe":
        return int(shortest_safe_policy.get(int(state), rng.randint(env.action_space.n)))
    if policy_name == "shortest_any":
        return int(shortest_any_policy.get(int(state), rng.randint(env.action_space.n)))
    if policy_name == "longest_safe":
        if path_step < len(longest_safe_path):
            return int(longest_safe_path[path_step])
        return int(shortest_safe_policy.get(int(state), rng.randint(env.action_space.n)))
    if policy_name == "longest_any":
        if path_step < len(longest_any_path):
            return int(longest_any_path[path_step])
        return int(shortest_any_policy.get(int(state), rng.randint(env.action_space.n)))
    return int(rng.randint(env.action_space.n))
